import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, stat, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";

export interface PwaBuildOptions {
  siteDir: string;
  scope: string;
  workerUrl: string;
  startUrl: string;
  name: string;
  shortName: string;
  description?: string;
  backgroundColor?: string;
  themeColor?: string;
  icons: Array<{ src: string; sizes: string; type: string; purpose?: string }>;
  offline: "shell" | "all_docs";
  assetDirectories: string[];
  assets: string[];
  maxPrecacheBytes: number;
}

function canonical(path: string): string {
  return path.length > 1 && path.endsWith("/") ? path.slice(0, -1) : path;
}

function inScope(path: string, scope: string): boolean {
  return scope === "/" || path === scope || path.startsWith(`${scope}/`);
}

function filePath(siteDir: string, url: string): string {
  if (!url.startsWith("/") || url.includes("?") || url.includes("#")) {
    throw new Error(`PWA asset must be a root-relative path: ${url}`);
  }
  const segments = url.slice(1).split("/");
  if (segments.some((segment) => segment === "." || segment === ".." || segment.includes("\\"))) {
    throw new Error(`PWA asset escapes the site directory: ${url}`);
  }
  return join(siteDir, ...segments);
}

async function filesUnder(directory: string): Promise<string[]> {
  const entries = await readdir(directory, { withFileTypes: true });
  const paths = await Promise.all(entries.map(async (entry) => {
    const path = join(directory, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`PWA input contains a symlink: ${path}`);
    return entry.isDirectory() ? filesUnder(path) : [path];
  }));
  return paths.flat().sort();
}

function workerSource(scope: string, version: string, paths: string[], docs: string[]): string {
  const base = scope === "/" ? "/" : `${scope}/`;
  const offlineUrl = `${base}offline.html`;
  const cachePrefix = `hydronium-pwa-${createHash("sha256").update(scope).digest("hex").slice(0, 12)}-`;
  return `// Generated from the final site output. Do not edit this file.
const SCOPE = ${JSON.stringify(scope)};
const CACHE = ${JSON.stringify(`${cachePrefix}${version}`)};
const CACHE_PREFIX = ${JSON.stringify(cachePrefix)};
const PRELOAD = ${JSON.stringify(paths)};
const PRECACHE = new Set(PRELOAD);
const DOCUMENTS = new Set(${JSON.stringify(docs)});
const OFFLINE = ${JSON.stringify(offlineUrl)};
const canonical = (path) => path.length > 1 && path.endsWith("/") ? path.slice(0, -1) : path;
const inScope = (path) => SCOPE === "/" || path === SCOPE || path.startsWith(SCOPE + "/");
const cacheKey = (url) => new Request(new URL(canonical(url.pathname), self.location.origin));
const cacheable = (response) => response.ok && response.type !== "opaque" &&
  !response.headers.get("Cache-Control")?.includes("no-store");
self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    for (let i = 0; i < PRELOAD.length; i += 8) {
      await cache.addAll(PRELOAD.slice(i, i + 8).map((path) =>
        new Request(path, { cache: "reload" })));
    }
  })());
});
self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) {
      if (name.startsWith(CACHE_PREFIX) && name !== CACHE) await caches.delete(name);
    }
    await self.clients.claim();
  })());
});
self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  const path = canonical(url.pathname);
  if (request.mode === "navigate") {
    if (!inScope(path)) return;
    event.respondWith((async () => {
      const key = cacheKey(url);
      try {
        const response = await fetch(request);
        if (DOCUMENTS.has(path) && cacheable(response)) {
          const cache = await caches.open(CACHE);
          await cache.put(key, response.clone());
        }
        return response;
      } catch {
        const cache = await caches.open(CACHE);
        return (await cache.match(key)) || (await cache.match(OFFLINE)) ||
          new Response("Documentation is unavailable offline.", { status: 503 });
      }
    })());
    return;
  }
  if (!PRECACHE.has(path)) return;
  event.respondWith((async () => {
    const key = cacheKey(url);
    const cache = await caches.open(CACHE);
    const cached = await cache.match(key);
    if (cached) return cached;
    const response = await fetch(request);
    if (cacheable(response)) await cache.put(key, response.clone());
    return response;
  })());
});
`;
}

/** Build a versioned, scope-limited offline worker from final rendered assets. */
export async function buildPwa(options: PwaBuildOptions): Promise<{ version: string; paths: string[]; bytes: number }> {
  const { siteDir, startUrl } = options;
  const scope = canonical(options.scope);
  const base = scope === "/" ? "/" : `${scope}/`;
  if (!scope.startsWith("/") || scope.includes("..") || options.scope !== scope) {
    throw new Error(`PWA scope must be a root-relative canonical path without a trailing slash: ${options.scope}`);
  }
  if (!inScope(startUrl, scope)) throw new Error(`PWA start URL is outside scope: ${startUrl}`);
  if (!options.icons.length) throw new Error("PWA needs at least one icon");
  const workerDirectory = options.workerUrl.slice(0, options.workerUrl.lastIndexOf("/") + 1);
  if (!options.workerUrl.endsWith(".js") || !scope.startsWith(workerDirectory)) {
    throw new Error(`PWA worker ${options.workerUrl} cannot control scope ${scope}`);
  }

  const scopeDirectory = filePath(siteDir, base);
  const htmlFiles = (await filesUnder(scopeDirectory)).filter((path) => path.endsWith(".html"));
  const docs = htmlFiles.filter((path) => !path.endsWith("offline.html")).map((path) => {
    const url = `/${relative(siteDir, path).split(sep).join("/")}`;
    return url.endsWith("/index.html") ? url.slice(0, -"/index.html".length) || "/" : url;
  }).sort();
  if (!docs.includes(canonical(startUrl))) {
    throw new Error(`PWA start URL has no rendered HTML: ${startUrl}`);
  }

  const offlineUrl = `${base}offline.html`;
  await writeFile(filePath(siteDir, offlineUrl),
    '<!doctype html><html lang="en"><meta charset="utf-8"><title>Offline</title>' +
    '<main><h1>Documentation is offline</h1><p>Reconnect to load this page.</p></main></html>\n');

  const paths = new Set<string>([canonical(startUrl), offlineUrl]);
  for (const icon of options.icons) paths.add(icon.src);
  for (const asset of options.assets) paths.add(asset);
  for (const dir of options.assetDirectories) {
    const root = filePath(siteDir, dir);
    for (const path of await filesUnder(root)) paths.add(`/${relative(siteDir, path).split(sep).join("/")}`);
  }
  if (options.offline === "all_docs") for (const doc of docs) paths.add(doc);

  const manifestUrl = `${base}manifest.webmanifest`;
  const manifest = {
    id: scope,
    name: options.name,
    short_name: options.shortName,
    description: options.description,
    start_url: startUrl,
    scope,
    display: "standalone",
    background_color: options.backgroundColor,
    theme_color: options.themeColor,
    icons: options.icons,
  };
  await writeFile(filePath(siteDir, manifestUrl), `${JSON.stringify(manifest, null, 2)}\n`);
  paths.add(manifestUrl);

  const sortedPaths = [...paths].sort();
  const hash = createHash("sha256");
  let bytes = 0;
  for (const url of sortedPaths) {
    const path = filePath(siteDir, url);
    const rendered = docs.includes(url) ? join(path, "index.html") : path;
    const info = await stat(rendered);
    if (!info.isFile()) throw new Error(`PWA asset is not a file: ${url}`);
    bytes += info.size;
    hash.update(url).update("\0").update(await readFile(rendered)).update("\0");
  }
  if (bytes > options.maxPrecacheBytes) {
    throw new Error(`PWA precache is ${bytes} bytes, above ${options.maxPrecacheBytes} byte limit`);
  }
  const version = hash.digest("hex").slice(0, 20);
  await mkdir(scopeDirectory, { recursive: true });
  await writeFile(filePath(siteDir, options.workerUrl), workerSource(scope, version, sortedPaths, docs));
  return { version, paths: sortedPaths, bytes };
}
